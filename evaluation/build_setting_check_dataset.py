def paragraphs(text):
    return [p for p in text.split("\n\n") if p.strip()]


def build(case):
    data = json.loads((DATASETS / f"{case['from']}.json").read_text())
    chapters = []
    for item in data["chapters"]:
        if item["number"] > case["chapter"]:
            continue
        body = item["body"]
        if item["number"] == case["chapter"]:
            for edit in case["edits"]:
                count = body.count(edit["old"])
                if count != 1:
                    raise SystemExit(f"{case['id']}: anchor found {count} times: {edit['old'][:40]!r}")
                body = body.replace(edit["old"], edit["new"])
        chapters.append({"key": f"c{item['number']}", "title": item["title"], "body": paragraphs(body)})
    settings = [
        {
            "key": s["key"], "title": s["title"], "folder": s["folder"],
            "properties": s.get("properties", []),
            "body": [s["body"]],
            "core": [0] if s["key"] == case["core"] else [],
        }
        for s in data["settings"]
    ]
    keys = {s["key"] for s in settings} | {c["key"] for c in chapters}
    checked = "\n\n".join(chapters[-1]["body"])
    for group in ("expect", "avoid", "may"):
        for entry in case[group]:
            for quote in entry["quote"]:
                if quote not in checked:
                    raise SystemExit(f"{case['id']}: {group} quote not in chapter: {quote!r}")
            for source in entry.get("sources", []):
                if source not in keys:
                    raise SystemExit(f"{case['id']}: unknown source {source}")
    if case["core"] not in {s["key"] for s in settings}:
        raise SystemExit(f"{case['id']}: unknown core setting {case['core']}")
    return {
        "id": case["id"], "title": case["title"], "work": case["from"], "chapter": case["chapter"],
        "locale": "ko", "settings": settings, "chapters": chapters,
        "expect": case["expect"], "avoid": case["avoid"], "may": case["may"],
        "edits": case["edits"],
    }


cases = [build(case) for case in CASES]
OUT.write_text(json.dumps({"cases": cases}, ensure_ascii=False, indent=1))
total = {"cases": len(cases), "expect": sum(len(c["expect"]) for c in cases), "avoid": sum(len(c["avoid"]) for c in cases),
         "may": sum(len(c["may"]) for c in cases)}
for c in cases:
    chars = sum(len(p) for ch in c["chapters"] for p in ch["body"]) + sum(len(s["body"][0]) for s in c["settings"])
    print(f"{c['id']:7} chapters={len(c['chapters']):3} settings={len(c['settings']):2} chars={chars:7,} expect={len(c['expect'])} avoid={len(c['avoid'])} may={len(c['may'])}")
print(total)
